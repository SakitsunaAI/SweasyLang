import Foundation

/// Transpiles a Sweasy Program AST into valid, idiomatic Swift 6 source code.
public final class Transpiler {
    private var indentLevel: Int = 0

    public init() {}

    private func indent() -> String {
        String(repeating: "    ", count: indentLevel)
    }

    public func transpile(_ program: Program) -> String {
        var lines: [String] = []
        lines.append("// =============================================================")
        lines.append("// Generated by the Sweasy Language Transpiler")
        lines.append("// Sweasy: The human-friendly, English-syntax programming language")
        lines.append("// Compiled target: Apple Swift 6")
        lines.append("// =============================================================")
        lines.append("")
        lines.append(SweasyRuntime.code)
        lines.append("")
        lines.append("// --- BEGIN SWEASY USER PROGRAM ---")

        for stmt in program.statements {
            lines.append(transpileStatement(stmt))
        }

        lines.append("// --- END SWEASY USER PROGRAM ---")
        return lines.joined(separator: "\n")
    }

    public func transpileStatement(_ statement: Statement) -> String {
        switch statement {
        case .say(let exprs):
            if exprs.isEmpty {
                return "\(indent())_sweasy_print(\"\")"
            }
            let args = exprs.map { transpileExpression($0) }.joined(separator: ", ")
            return "\(indent())_sweasy_print(\(args))"

        case .setVariable(let name, let value, let isConstant):
            let keyword = isConstant ? "let" : "var"
            return "\(indent())\(keyword) \(name) = \(transpileExpression(value))"

        case .changeVariable(let name, let value):
            return "\(indent())\(name) = \(transpileExpression(value))"

        case .mutateVariable(let name, let op, let value):
            return "\(indent())\(name) \(op.rawValue) \(transpileExpression(value))"

        case .askUser(let target, let prompt, let type):
            switch type {
            case .string:
                return "\(indent())var \(target) = _sweasy_ask(\(transpileExpression(prompt)))"
            case .number:
                return "\(indent())var \(target) = _sweasy_ask_number(\(transpileExpression(prompt)))"
            case .integer:
                return "\(indent())var \(target) = _sweasy_ask_int(\(transpileExpression(prompt)))"
            }

        case .ifCondition(let cond, let thenBranch, let elseIfs, let elseBranch):
            var lines: [String] = []
            lines.append("\(indent())if \(transpileExpression(cond)) {")
            indentLevel += 1
            for s in thenBranch {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1

            for elseIf in elseIfs {
                lines.append("\(indent())} else if \(transpileExpression(elseIf.condition)) {")
                indentLevel += 1
                for s in elseIf.body {
                    lines.append(transpileStatement(s))
                }
                indentLevel -= 1
            }

            if let elseBranch = elseBranch {
                lines.append("\(indent())} else {")
                indentLevel += 1
                for s in elseBranch {
                    lines.append(transpileStatement(s))
                }
                indentLevel -= 1
            }
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .repeatCount(let times, let body):
            var lines: [String] = []
            lines.append("\(indent())for _ in 0..<Int(\(transpileExpression(times))) {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .repeatRange(let variable, let from, let to, let body):
            var lines: [String] = []
            lines.append("\(indent())for \(variable) in \(transpileExpression(from))...\(transpileExpression(to)) {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .repeatInfinite(let body):
            var lines: [String] = []
            lines.append("\(indent())while true {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .forEach(let variable, let collection, let body):
            var lines: [String] = []
            lines.append("\(indent())for \(variable) in \(transpileExpression(collection)) {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .whileLoop(let cond, let body):
            var lines: [String] = []
            lines.append("\(indent())while \(transpileExpression(cond)) {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .breakLoop:
            return "\(indent())break"

        case .continueLoop:
            return "\(indent())continue"

        case .returnStatement(let expr):
            if let expr = expr {
                return "\(indent())return \(transpileExpression(expr))"
            }
            return "\(indent())return"

        case .functionDefinition(let name, let parameters, let returnType, let body):
            var ret = returnType
            if ret == nil && containsReturnValue(body) {
                ret = "Any"
            }
            let retClause = ret != nil ? " -> \(ret!)" : ""
            let paramsStr = parameters.map { "_ \($0.name): \($0.typeName)" }.joined(separator: ", ")

            var lines: [String] = []
            lines.append("\(indent())func \(name)(\(paramsStr))\(retClause) {")
            indentLevel += 1
            for s in body {
                lines.append(transpileStatement(s))
            }
            indentLevel -= 1
            lines.append("\(indent())}")
            return lines.joined(separator: "\n")

        case .functionCall(let name, let arguments):
            let argsStr = arguments.map { transpileExpression($0) }.joined(separator: ", ")
            return "\(indent())\(name)(\(argsStr))"

        case .listAdd(let item, let list):
            return "\(indent())_sweasy_add(\(transpileExpression(item)), to: &\(list))"

        case .listRemove(let item, let list):
            return "\(indent())_sweasy_remove(\(transpileExpression(item)), from: &\(list))"

        case .listRemoveAt(let index, let list):
            return "\(indent())_sweasy_remove_at(Int(\(transpileExpression(index))), from: &\(list))"

        case .listClear(let list):
            return "\(indent())\(list).removeAll()"

        case .listSort(let list):
            return "\(indent())\(list).sort()"

        case .listReverse(let list):
            return "\(indent())\(list).reverse()"

        case .wait(let seconds):
            return "\(indent())_sweasy_wait(seconds: Double(\(transpileExpression(seconds))))"

        case .getRandom(let from, let to, let target, let isDouble):
            if isDouble {
                return "\(indent())var \(target) = _sweasy_random_number(from: Double(\(transpileExpression(from))), to: Double(\(transpileExpression(to))))"
            } else {
                return "\(indent())var \(target) = _sweasy_random_int(from: Int(\(transpileExpression(from))), to: Int(\(transpileExpression(to))))"
            }

        case .getDate(let target):
            return "\(indent())var \(target) = _sweasy_date()"

        case .getTime(let target):
            return "\(indent())var \(target) = _sweasy_time()"

        case .writeFile(let content, let path):
            return "\(indent())_ = _sweasy_write_file(\(transpileExpression(content)), to: \(transpileExpression(path)))"

        case .appendFile(let content, let path):
            return "\(indent())_ = _sweasy_append_file(\(transpileExpression(content)), to: \(transpileExpression(path)))"

        case .readFile(let path, let target):
            return "\(indent())var \(target) = _sweasy_read_file(\(transpileExpression(path)))"

        case .checkFileExists(let path, let target):
            return "\(indent())var \(target) = _sweasy_file_exists(\(transpileExpression(path)))"

        case .deleteFile(let path):
            return "\(indent())_ = _sweasy_delete_file(\(transpileExpression(path)))"

        case .fetchURL(let url, let target):
            return "\(indent())var \(target) = _sweasy_fetch_url(\(transpileExpression(url)))"

        case .shellCommand(let command, let target):
            return "\(indent())var \(target) = _sweasy_shell(\(transpileExpression(command)))"

        case .exitProgram:
            return "\(indent())exit(0)"

        case .rawSwift(let code):
            let codeLines = code.components(separatedBy: .newlines)
            return codeLines.map { "\(indent())\($0)" }.joined(separator: "\n")

        case .expressionStatement(let expr):
            return "\(indent())\(transpileExpression(expr))"
        }
    }

    public func transpileExpression(_ expr: Expression) -> String {
        switch expr {
        case .literalString(let s):
            return ExpressionParser.transformStringLiteral("\"\(s)\"")
        case .literalInt(let i):
            return "\(i)"
        case .literalDouble(let d):
            return "\(d)"
        case .literalBool(let b):
            return b ? "true" : "false"
        case .literalList(let items):
            let inner = items.map { transpileExpression($0) }.joined(separator: ", ")
            return "[\(inner)]"
        case .literalDict(let pairs):
            let inner = pairs.map { "\(transpileExpression($0.key)): \(transpileExpression($0.value))" }.joined(separator: ", ")
            return "[\(inner)]"
        case .variable(let name):
            return name
        case .binary(let left, let op, let right):
            return "(\(transpileExpression(left)) \(op.rawValue) \(transpileExpression(right)))"
        case .unary(let op, let sub):
            return "\(op.rawValue)(\(transpileExpression(sub)))"
        case .call(let name, let args):
            let inner = args.map { transpileExpression($0) }.joined(separator: ", ")
            return "\(name)(\(inner))"
        case .indexAccess(let base, let idx):
            return "\(transpileExpression(base))[\(transpileExpression(idx))]"
        case .firstItem(let sub):
            return "_sweasy_first(\(transpileExpression(sub)))"
        case .lastItem(let sub):
            return "_sweasy_last(\(transpileExpression(sub)))"
        case .countOf(let sub):
            return "_sweasy_length(\(transpileExpression(sub)))"
        case .uppercaseOf(let sub):
            return "_sweasy_uppercase(\(transpileExpression(sub)))"
        case .lowercaseOf(let sub):
            return "_sweasy_lowercase(\(transpileExpression(sub)))"
        case .mathFunc(let name, let arg):
            return "\(name)(\(transpileExpression(arg)))"
        case .rawSwift(let code):
            return code
        }
    }

    private func containsReturnValue(_ statements: [Statement]) -> Bool {
        for s in statements {
            switch s {
            case .returnStatement(let expr):
                if expr != nil { return true }
            case .ifCondition(_, let thenB, let elseIfs, let elseB):
                if containsReturnValue(thenB) { return true }
                for elseIf in elseIfs {
                    if containsReturnValue(elseIf.body) { return true }
                }
                if let elseB = elseB, containsReturnValue(elseB) { return true }
            case .repeatCount(_, let body),
                 .repeatRange(_, _, _, let body),
                 .repeatInfinite(let body),
                 .forEach(_, _, let body),
                 .whileLoop(_, let body):
                if containsReturnValue(body) { return true }
            default:
                break
            }
        }
        return false
    }
}
